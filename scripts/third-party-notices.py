DESKTOP_TARGETS = [
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "x86_64-pc-windows-msvc",
    "x86_64-unknown-linux-gnu",
]


# Crates that vendor C sources keep the upstream licence below the crate root.
VENDORED = ("upstream",)


def license_texts(directory: Path) -> list[tuple[str, str]]:
    """(file name, text) of the licence/notice files at the top of `directory`
    and of its vendored upstream sources."""
    found = []
    for d in (directory, *(directory / v for v in VENDORED)):
        if d.is_dir():
            for f in sorted(d.iterdir()):
                if f.is_file() and LICENSE_FILE.match(f.name):
                    name = str(f.relative_to(directory))
                    found.append((name, f.read_text(encoding="utf-8", errors="replace").strip()))
    return found


def rust_packages() -> list[dict]:
    """Normal dependencies of the `facetimelapse` binary on any desktop target."""
    ids: set[str] = set()
    packages: dict[str, dict] = {}
    for target in DESKTOP_TARGETS:
        meta = json.loads(
            subprocess.run(
                ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
                cwd=ROOT,
                check=True,
                capture_output=True,
                text=True,
            ).stdout
        )
        packages.update({p["id"]: p for p in meta["packages"]})
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        root = next(p["id"] for p in meta["packages"] if p["name"] == "facetimelapse")
        stack = [root]
        while stack:
            pid = stack.pop()
            if pid in ids:
                continue
            ids.add(pid)
            for dep in nodes[pid]["deps"]:
                if any(k["kind"] in (None, "normal") for k in dep["dep_kinds"]):
                    stack.append(dep["pkg"])
    third = [packages[i] for i in ids if packages[i].get("source")]
    return sorted(third, key=lambda p: (p["name"], p["version"]))


def npm_packages() -> list[dict]:
    """Production dependencies of the UI, transitively, from ui/node_modules."""
    modules = ROOT / "ui" / "node_modules"
    top = json.loads((ROOT / "ui" / "package.json").read_text())
    seen: dict[str, dict] = {}
    stack = list(top.get("dependencies", {}))
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        manifest = modules / name / "package.json"
        if not manifest.is_file():
            sys.exit(f"missing {manifest}: run `npm --prefix ui ci` first")
        pkg = json.loads(manifest.read_text())
        pkg["_dir"] = manifest.parent
        seen[name] = pkg
        stack.extend(pkg.get("dependencies", {}))
    return sorted(seen.values(), key=lambda p: p["name"])


def normalized(text: str) -> str:
    return "\n".join(line.rstrip() for line in text.splitlines()).strip()


def section(title: str, entries: list[tuple[str, str, str, list[tuple[str, str]]]]) -> str:
    """Component index, then every distinct licence/notice text once with the
    components that ship it (identical Apache-2.0 texts collapse into one)."""
    texts: dict[str, int] = {}
    users: dict[int, list[str]] = {}
    files: dict[int, set[str]] = {}
    index = []
    for name, version, license_id, found in entries:
        refs = []
        for file_name, text in found:
            key = normalized(text)
            n = texts.setdefault(key, len(texts) + 1)
            users.setdefault(n, []).append(f"{name} {version}")
            files.setdefault(n, set()).add(file_name)
            refs.append(f"[{n}]")
        shown = " ".join(refs) if refs else "(no licence file in the package)"
        index.append(f"  {name} {version} — {license_id} {shown}")
    out = [title, "-" * len(title), "", "Components (name version — license [texts]):", *index, ""]
    for key, n in texts.items():
        out.append("=" * 78)
        out.append(f"[{n}] {', '.join(sorted(files[n]))} — shipped by: {', '.join(users[n])}")
        out.append("")
        out.append(key)
        out.append("")
    return "\n".join(out)


def main() -> None:
    rust = [
        (p["name"], p["version"], p.get("license") or "see license file",
         license_texts(Path(p["manifest_path"]).parent))
        for p in rust_packages()
    ]
    npm = [
        (p["name"], p["version"], p.get("license") or "see license file", license_texts(p["_dir"]))
        for p in npm_packages()
    ]
    text = "\n".join(
        [
            HEADER,
            section(f"4. Rust crates linked into the application ({len(rust)})", rust),
            section(f"5. JavaScript packages bundled into the user interface ({len(npm)})", npm),
        ]
    )
    (OUT_DIR / "THIRD-PARTY-NOTICES.txt").write_text(text.rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT_DIR / 'THIRD-PARTY-NOTICES.txt'}: {len(rust)} crates, {len(npm)} npm packages")


if __name__ == "__main__":
    main()
